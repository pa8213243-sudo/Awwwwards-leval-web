export const PixelTypography: React.FC<PixelTypographyProps> = ({
  text,
  className = '',
  progress = 1,
  size = 'md',
  activeColor = 'bg-[#E0533C]',
}) => {
  const chars = text.toUpperCase().split('');

  const sizeClasses = {
    sm: 'w-1 h-1 gap-0.5',
    md: 'w-1.5 h-1.5 sm:w-2 sm:h-2 gap-0.5 sm:gap-1',
    lg: 'w-2 h-2 sm:w-3 sm:h-3 md:w-4 md:h-4 gap-1 md:gap-1.5',
    xl: 'w-2.5 h-2.5 sm:w-4 sm:h-4 md:w-5 md:h-5 lg:w-6 lg:h-6 gap-1 md:gap-2',
  };

  const totalDots = chars.length * 25;
  const dotsToReveal = Math.floor(totalDots * Math.min(1, Math.max(0, progress)));

  let dotCounter = 0;

  return (
    <div className={`inline-flex items-center gap-3 sm:gap-6 flex-wrap select-none ${className}`}>
      {chars.map((char, charIdx) => {
        const pattern = MATRIX_PATTERNS[char] || MATRIX_PATTERNS[' '];

        return (
          <div key={charIdx} className="grid grid-cols-5 gap-1">
            {pattern.map((row, rowIdx) =>
              row.map((val, colIdx) => {
                dotCounter++;
                const isRevealed = dotCounter <= dotsToReveal;
                const isActive = val === 1;

                return (
                  <div
                    key={`${rowIdx}-${colIdx}`}
                    className={`${sizeClasses[size].split(' ')[0]} ${sizeClasses[size].split(' ')[1]} transition-all duration-300 rounded-[1px] ${
                      isActive
                        ? isRevealed
                          ? `${activeColor} shadow-[0_0_10px_rgba(224,83,60,0.6)] opacity-100 scale-100`
                          : 'bg-white/20 opacity-30 scale-90'
                        : 'bg-white/5 opacity-10'
                    }`}
                  />
                );
              })
            )}
          </div>
        );
      })}
    </div>
  );
};
